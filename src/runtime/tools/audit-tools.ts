import type { Tool } from "@mozaik-ai/core"
import { z } from "zod"
import {
	computeCentProofVarianceMinor,
	computeRecoverableOurViolationMinor,
	formatMoney,
} from "../../core/money"
import type { AuditStatus, AuditVerdict, SourceRef } from "../../core/types"
import { resolveRuntime } from "../corridor-runtime"

const CaseIdSchema = z.object({ caseId: z.string() })
const FinalizeSchema = z.object({
	caseId: z.string(),
	actionType: z
		.enum(["CLOSE_CLEAN", "FILE_OUR_FEE_DISPUTE", "ESCALATE_VARIANCE", "AUTO_FROM_AUDIT"])
		.optional(),
	recoverableMinor: z.number().optional(),
	currency: z.string().optional(),
	summary: z.string().optional(),
	disputeDraft: z.string().optional(),
	humanOverrideNote: z.string().optional(),
})

function dedupeSourceRefs(refs: SourceRef[]): SourceRef[] {
	const seen = new Set<string>()
	const out: SourceRef[] = []
	for (const r of refs) {
		const key = `${r.sourceType}|${r.recordId}|${r.field}|${r.rawExcerpt}`
		if (!seen.has(key)) {
			seen.add(key)
			out.push(r)
		}
	}
	return out
}

function buildDisputeLetter(params: {
	caseId: string
	invoiceId: string
	wireId: string
	transactionRef: string
	valueDate: string
	senderName: string
	recoverableFormatted: string
	contractBearer: string
}): string {
	return [
		`SUBJECT: Formal Fee Recovery Request — ${params.invoiceId} / Wire Ref ${params.transactionRef}`,
		`DATE: ${new Date().toISOString().slice(0, 10)}`,
		``,
		`To: Correspondent & Operations Fee Investigations Desk (${params.senderName})`,
		``,
		`We request reimbursement of ${params.recoverableFormatted} wrongfully deducted from cross-border wire ${params.wireId} (Ref: ${params.transactionRef}, Value Date: ${params.valueDate}).`,
		``,
		`EVIDENCE SUMMARY:`,
		`- Underlying Invoice: ${params.invoiceId}`,
		`- SWIFT Field :71A: / Contract Charge Clause: ${params.contractBearer} (all correspondent and intermediary charges must be borne by the ordering party, zero beneficiary deduction).`,
		`- Deducted Amount Cleared in Error: ${params.recoverableFormatted}`,
		``,
		`Please credit ${params.recoverableFormatted} back to the beneficiary account and confirm the adjustment reference.`,
		``,
		`---`,
		`Generated by CorridorAudit · Synthetic & public ECB data demonstration only. Not financial or legal advice.`,
	].join("\n")
}

export const verifySettlementBalanceTool: Tool = {
	type: "function",
	name: "verify_settlement_balance",
	description: "Deterministically cross-check TermsAgent, FxBenchmarkAgent, WireDetectiveAgent, and DuplicateAnomalyAgent in integer minor units.",
	parameters: {
		type: "object",
		properties: { caseId: { type: "string" } },
		required: ["caseId"],
	},
	strict: false,
	invoke: async (rawArgs: unknown) => {
		const { caseId } = CaseIdSchema.parse(rawArgs)
		const state = resolveRuntime().state
		const c = state.casesById.get(caseId)
		const terms = state.termsByCaseId.get(caseId)
		const fx = state.fxByCaseId.get(caseId)
		const wire = state.wireByCaseId.get(caseId)
		const anomaly = state.anomalyByCaseId.get(caseId)

		if (!c || !terms || !fx || !wire) {
			return {
				caseId,
				error: "Specialist assessments incomplete before Auditor verification.",
			}
		}

		const targetCcy = c.wire.settledAmount.currency
		const deductedFeesMinor =
			wire.normalizedReceiverFeesMinor + wire.normalizedRepairFeeMinor + wire.normalizedPlatformFeeMinor
		const varianceMinor = computeCentProofVarianceMinor({
			midMarketExpectedMinor: fx.midMarketExpectedMinor,
			fxSpreadLossMinor: fx.fxSpreadLossMinor,
			deductedFeesMinor,
			withholdingTaxMinor: terms.withholdingTaxMinor,
			netSettledMinor: c.wire.settledAmount.amountMinor,
		})

		const recoverableOurViolationMinor = computeRecoverableOurViolationMinor({
			contractedBearer: terms.contractedChargeBearer,
			wireBearer: c.wire.chargeBearer,
			normalizedReceiverChargesMinor: wire.normalizedReceiverFeesMinor,
			normalizedRepairFeeMinor: wire.normalizedRepairFeeMinor,
		})

		const duplicateDetected = anomaly?.classification === "TRUE_DUPLICATE"
		const recommendedAction =
			recoverableOurViolationMinor > 0
				? "FILE_OUR_FEE_DISPUTE"
				: varianceMinor !== 0 || duplicateDetected || Boolean(anomaly?.vendorBankChanged)
					? "ESCALATE_VARIANCE"
					: "CLOSE_CLEAN"

		return {
			caseId,
			currency: targetCcy,
			midMarketExpectedMinor: fx.midMarketExpectedMinor,
			fxSpreadLossMinor: fx.fxSpreadLossMinor,
			fxSpreadBps: fx.fxSpreadBps,
			deductedFeesMinor,
			withholdingTaxMinor: terms.withholdingTaxMinor,
			settledMinor: c.wire.settledAmount.amountMinor,
			unexplainedVarianceMinor: varianceMinor,
			recoverableOurViolationMinor,
			duplicateDetected,
			ibanValid: terms.ibanValid ?? true,
			isOrphanMatched: wire.isOrphan && Boolean(wire.matchedInvoiceId),
			recommendedAction,
			summary: `Cent-proof balance verified in ${targetCcy}: ECB ${formatMoney(fx.midMarketExpectedMinor, targetCcy)} - FX ${formatMoney(fx.fxSpreadLossMinor, targetCcy)} - Fees ${formatMoney(deductedFeesMinor, targetCcy)} - Net ${formatMoney(c.wire.settledAmount.amountMinor, targetCcy)} => Variance ${formatMoney(varianceMinor, targetCcy)}.`,
		}
	},
}

export const verifyCitationsIntegrityTool: Tool = {
	type: "function",
	name: "verify_citations_integrity",
	description: "Verify all specialist findings carry non-empty grounded SourceRef citations with zero fabricated numbers.",
	parameters: {
		type: "object",
		properties: { caseId: { type: "string" } },
		required: ["caseId"],
	},
	strict: false,
	invoke: async (rawArgs: unknown) => {
		const { caseId } = CaseIdSchema.parse(rawArgs)
		const state = resolveRuntime().state
		const terms = state.termsByCaseId.get(caseId)
		const fx = state.fxByCaseId.get(caseId)
		const wire = state.wireByCaseId.get(caseId)
		const anomaly = state.anomalyByCaseId.get(caseId)

		const allRefs = dedupeSourceRefs([
			...(terms?.sourceRefs ?? []),
			...(fx?.sourceRefs ?? []),
			...(wire?.sourceRefs ?? []),
			...(anomaly?.sourceRefs ?? []),
		])

		const validRefs = allRefs.filter(
			(r) => Boolean(r.sourceType && r.recordId && r.field && r.rawExcerpt.trim().length > 0),
		)
		const citationAuditPassed = validRefs.length >= 2

		return {
			caseId,
			citationAuditPassed,
			totalRefs: validRefs.length,
			sourceRefs: validRefs,
			summary: citationAuditPassed
				? `Citation integrity PASSED: ${validRefs.length}/${validRefs.length} SourceRefs verified against raw evidence.`
				: "Citation integrity FAILED: insufficient grounded SourceRefs.",
		}
	},
}

export const simulateCorridorReplayTool: Tool = {
	type: "function",
	name: "simulate_corridor_replay",
	description: "Compute actual net landed vs optimal transparent ECB + enforced OUR corridor replay savings.",
	parameters: {
		type: "object",
		properties: { caseId: { type: "string" } },
		required: ["caseId"],
	},
	strict: false,
	invoke: async (rawArgs: unknown) => {
		const { caseId } = CaseIdSchema.parse(rawArgs)
		const state = resolveRuntime().state
		const c = state.casesById.get(caseId)
		const fx = state.fxByCaseId.get(caseId)
		const wire = state.wireByCaseId.get(caseId)
		if (!c || !fx || !wire) return { error: `Missing assessments for ${caseId}` }

		const to = c.wire.settledAmount.currency
		const actualNetMinor = c.wire.settledAmount.amountMinor
		const optimalTransparentNetMinor = fx.midMarketExpectedMinor
		const totalLeakMinor = Math.max(0, optimalTransparentNetMinor - actualNetMinor)
		const totalLeakBps =
			optimalTransparentNetMinor > 0
				? Math.round((totalLeakMinor / optimalTransparentNetMinor) * 10000)
				: 0

		return {
			caseId,
			currency: to,
			actualNetMinor,
			actualNetFormatted: formatMoney(actualNetMinor, to),
			optimalTransparentNetMinor,
			optimalNetFormatted: formatMoney(optimalTransparentNetMinor, to),
			totalLeakMinor,
			totalLeakFormatted: formatMoney(totalLeakMinor, to),
			totalLeakBps,
			summary: `Corridor Replay: Actual ${formatMoney(actualNetMinor, to)} vs Transparent ${formatMoney(optimalTransparentNetMinor, to)} -> preventable/recoverable leak ${formatMoney(totalLeakMinor, to)} (${(totalLeakBps / 100).toFixed(2)}%).`,
		}
	},
}

export const finalizeSettlementActionTool: Tool = {
	type: "function",
	name: "finalize_settlement_action",
	description: "Persist final verified AuditVerdict & dispute claim draft to CorridorState. Guarded by Mozaik SettlementGateInterceptionHandler!",
	parameters: {
		type: "object",
		properties: {
			caseId: { type: "string" },
			actionType: { type: "string", enum: ["CLOSE_CLEAN", "FILE_OUR_FEE_DISPUTE", "ESCALATE_VARIANCE", "AUTO_FROM_AUDIT"] },
			recoverableMinor: { type: "number" },
			currency: { type: "string" },
			summary: { type: "string" },
			disputeDraft: { type: "string" },
			humanOverrideNote: { type: "string" },
		},
		required: ["caseId"],
	},
	strict: false,
	invoke: async (rawArgs: unknown) => {
		const args = FinalizeSchema.parse(rawArgs)
		const state = resolveRuntime().state
		const c = state.casesById.get(args.caseId)
		const terms = state.termsByCaseId.get(args.caseId)
		const fx = state.fxByCaseId.get(args.caseId)
		const wire = state.wireByCaseId.get(args.caseId)
		const anomaly = state.anomalyByCaseId.get(args.caseId)

		if (!c || !terms || !fx || !wire) {
			return { error: `Cannot finalize ${args.caseId}: missing specialist results.` }
		}

		const to = c.wire.settledAmount.currency
		const deductedFeesMinor =
			wire.normalizedReceiverFeesMinor + wire.normalizedRepairFeeMinor + wire.normalizedPlatformFeeMinor
		const varianceMinor = computeCentProofVarianceMinor({
			midMarketExpectedMinor: fx.midMarketExpectedMinor,
			fxSpreadLossMinor: fx.fxSpreadLossMinor,
			deductedFeesMinor,
			withholdingTaxMinor: terms.withholdingTaxMinor,
			netSettledMinor: c.wire.settledAmount.amountMinor,
		})

		const overriddenClean = args.actionType === "CLOSE_CLEAN" || Boolean(args.humanOverrideNote)
		const recoverableFeeMinor = overriddenClean
			? 0
			: computeRecoverableOurViolationMinor({
					contractedBearer: terms.contractedChargeBearer,
					wireBearer: c.wire.chargeBearer,
					normalizedReceiverChargesMinor: wire.normalizedReceiverFeesMinor,
					normalizedRepairFeeMinor: wire.normalizedRepairFeeMinor,
				})

		let status: AuditStatus = "CLEAN"
		if (anomaly?.classification === "TRUE_DUPLICATE") status = "DUPLICATE_WIRE"
		else if (recoverableFeeMinor > 0) status = "RECOVERABLE_FEE_VIOLATION"
		else if (varianceMinor !== 0) status = "VARIANCE_DETECTED"
		else if (wire.isOrphan && wire.matchedInvoiceId) status = "ORPHAN_MATCHED"
		else if (fx.fxSpreadBps >= 150) status = "FX_MARKUP_ALERT"

		const totalLeakMinor = Math.max(0, fx.midMarketExpectedMinor - c.wire.settledAmount.amountMinor)
		const totalLeakBps =
			fx.midMarketExpectedMinor > 0 ? Math.round((totalLeakMinor / fx.midMarketExpectedMinor) * 10000) : 0

		const allRefs = dedupeSourceRefs([
			...terms.sourceRefs,
			...fx.sourceRefs,
			...wire.sourceRefs,
			...(anomaly?.sourceRefs ?? []),
		])

		const defaultSummary =
			args.summary ||
			(() => {
				const parts: string[] = [
					`Invoice ${wire.matchedInvoiceId ?? terms.invoiceId} (${formatMoney(terms.expectedGrossMinor, terms.expectedCurrency)}, ${terms.contractedChargeBearer}) settled at ${formatMoney(c.wire.settledAmount.amountMinor, to)}.`,
				]
				if (fx.fxSpreadLossMinor > 0) {
					parts.push(`Bank FX spread cost ${formatMoney(fx.fxSpreadLossMinor, to)} (${(fx.fxSpreadBps / 100).toFixed(2)}%) vs ECB ${fx.rateRecord.midMarketRate}.`)
				}
				if (recoverableFeeMinor > 0) {
					parts.push(`Wrongful :71A:OUR deduction of ${formatMoney(recoverableFeeMinor, to)} is recoverable.`)
				}
				if (varianceMinor !== 0) {
					parts.push(`Unexplained short-pay variance: ${formatMoney(varianceMinor, to)}.`)
				} else {
					parts.push(`Cent-proof variance: ${formatMoney(0, to)}.`)
				}
				if (args.humanOverrideNote) {
					parts.push(`Operator note applied: "${args.humanOverrideNote}".`)
				}
				return parts.join(" ")
			})()

		const disputeNotice =
			recoverableFeeMinor > 0
				? args.disputeDraft ||
					buildDisputeLetter({
						caseId: args.caseId,
						invoiceId: wire.matchedInvoiceId ?? terms.invoiceId,
						wireId: c.wire.wireId,
						transactionRef: c.wire.transactionRef ?? c.wire.wireId,
						valueDate: c.wire.valueDate,
						senderName: c.wire.senderName ?? c.invoice?.vendorOrClient ?? "Originating Bank",
						recoverableFormatted: formatMoney(recoverableFeeMinor, to),
						contractBearer: terms.contractedChargeBearer,
					})
				: undefined

		const verdict: AuditVerdict = {
			caseId: args.caseId,
			invoiceId: wire.matchedInvoiceId ?? terms.invoiceId,
			wireId: c.wire.wireId,
			status,
			plainEnglishSummary: defaultSummary,
			numbers: {
				invoicedMinor: terms.expectedGrossMinor,
				invoicedCurrency: terms.expectedCurrency,
				midMarketEquivalentMinor: fx.midMarketExpectedMinor,
				settledMinor: c.wire.settledAmount.amountMinor,
				settledCurrency: to,
				fxSpreadLossMinor: fx.fxSpreadLossMinor,
				fxSpreadBps: fx.fxSpreadBps,
				liftingAndRepairFeesMinor: wire.normalizedReceiverFeesMinor + wire.normalizedRepairFeeMinor,
				platformFeeMinor: wire.normalizedPlatformFeeMinor,
				withholdingTaxMinor: terms.withholdingTaxMinor,
				recoverableFeeMinor,
				unexplainedVarianceMinor: varianceMinor,
			},
			replay: {
				actualNetMinor: c.wire.settledAmount.amountMinor,
				optimalTransparentNetMinor: fx.midMarketExpectedMinor,
				totalLeakMinor,
				totalLeakBps,
			},
			sourceRefs: allRefs,
			disputeNotice,
			humanOverrideNote: args.humanOverrideNote,
			disclaimer: "Synthetic/public data demonstration only. Not financial or legal advice.",
			completedAt: new Date().toISOString(),
		}

		state.auditByCaseId.set(args.caseId, verdict)
		state.emitTrajectory({
			caseId: args.caseId,
			kind: "ledger.entry",
			status: status === "CLEAN" || status === "ORPHAN_MATCHED" ? "ok" : status === "VARIANCE_DETECTED" ? "bad" : "warn",
			text: `${args.caseId} finalized as ${status} (Recoverable: ${formatMoney(recoverableFeeMinor, to)}, Variance: ${formatMoney(varianceMinor, to)})`,
		})
		state.emitTrajectory({
			caseId: args.caseId,
			kind: "audit.verdict",
			payload: { verdict },
		})
		state.resolveCaseWaiters(args.caseId, verdict)

		return {
			caseId: args.caseId,
			status,
			verdict,
			sourceRefs: allRefs,
		}
	},
}


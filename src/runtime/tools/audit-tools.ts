const CaseIdSchema = z.object({ caseId: z.string() })
const FinalizeSchema = z.object({
	caseId: z.string(),
	actionType: z
		.enum(["CLOSE_CLEAN", "FILE_OUR_FEE_DISPUTE", "ESCALATE_VARIANCE", "AUTO_FROM_AUDIT"])
		.optional(),
	recoverableMinor: z.number().optional(),
	currency: z.string().optional(),
	summary: z.string().optional(),
	disputeDraft: z.string().optional(),
	humanOverrideNote: z.string().optional(),
})

function dedupeSourceRefs(refs: SourceRef[]): SourceRef[] {
	const seen = new Set<string>()
	const out: SourceRef[] = []
	for (const r of refs) {
		const key = `${r.sourceType}|${r.recordId}|${r.field}|${r.rawExcerpt}`
		if (!seen.has(key)) {
			seen.add(key)
			out.push(r)
		}
	}
	return out
}

function buildDisputeLetter(params: {
	caseId: string
	invoiceId: string
	wireId: string
	transactionRef: string
	valueDate: string
	senderName: string
	recoverableFormatted: string
	contractBearer: string
	provenanceLabel: string
	auditRulesVersion: string
}): string {
	return [
		`SUBJECT: Request to Review Potential Fee Discrepancy - ${params.invoiceId} / Wire Ref ${params.transactionRef}`,
		`DATE: ${new Date().toISOString().slice(0, 10)}`,
		``,
		`To: Correspondent & Operations Fee Investigations Desk (${params.senderName})`,
		``,
		`Based on the records supplied, we request a review of ${params.recoverableFormatted} in charges applied to cross-border wire ${params.wireId} (Ref: ${params.transactionRef}, Value Date: ${params.valueDate}).`,
		``,
		`EVIDENCE SUMMARY:`,
		`- Underlying Invoice: ${params.invoiceId}`,
		`- Submitted invoice or contract terms recorded for review: ${params.contractBearer}.`,
		`- Potential discrepancy calculated from the submitted records: ${params.recoverableFormatted}`,
		``,
		`Please review the attached transaction records and advise whether an adjustment is due. If confirmed, please credit ${params.recoverableFormatted} to the beneficiary account and provide the adjustment reference.`,
		``,
		`Build: ${params.provenanceLabel} · Audit rules: v${params.auditRulesVersion}`,
		`---`,
		`Generated by CorridorAudit as a review draft from submitted records and the cited ECB reference data. Confirm the original contract, bank statement, recipient, and amounts before sending. This document is not independent bank confirmation or financial or legal advice.`,
	].join("\n")
}

export function computeCaseAuditNumbers(state: CorridorState, caseId: string) {
	const c = state.casesById.get(caseId)
	const terms = state.termsByCaseId.get(caseId)
	const fx = state.fxByCaseId.get(caseId)
	const wire = state.wireByCaseId.get(caseId)
	const anomaly = state.anomalyByCaseId.get(caseId)
	if (!c || !terms || !fx || !wire) return null

	const targetCcy = c.wire.settledAmount.currency
	const deductedFeesMinor =
		wire.normalizedReceiverFeesMinor + wire.normalizedRepairFeeMinor + wire.normalizedPlatformFeeMinor
	const normalizedWithholdingTaxMinor =
		terms.withholdingTaxMinor > 0
			? convertMinorUnits(
					terms.withholdingTaxMinor,
					terms.expectedCurrency,
					targetCcy,
					terms.expectedCurrency.toUpperCase() === targetCcy.toUpperCase() ? 1 : fx.rateRecord.midMarketRate,
				)
			: 0
	const varianceMinor = computeCentProofVarianceMinor({
		midMarketExpectedMinor: fx.midMarketExpectedMinor,
		fxSpreadLossMinor: fx.fxSpreadLossMinor,
		deductedFeesMinor,
		withholdingTaxMinor: normalizedWithholdingTaxMinor,
		netSettledMinor: c.wire.settledAmount.amountMinor,
	})
	const recoverableOurViolationMinor = computeRecoverableOurViolationMinor({
		contractedBearer: terms.contractedChargeBearer,
		wireBearer: c.wire.chargeBearer,
		normalizedReceiverChargesMinor: wire.normalizedReceiverFeesMinor,
		normalizedRepairFeeMinor: wire.normalizedRepairFeeMinor,
	})
	const optimalTransparentNetMinor = Math.max(0, fx.midMarketExpectedMinor - normalizedWithholdingTaxMinor)
	const totalLeakMinor = Math.max(0, optimalTransparentNetMinor - c.wire.settledAmount.amountMinor)
	const totalLeakBps =
		optimalTransparentNetMinor > 0 ? Math.round((totalLeakMinor / optimalTransparentNetMinor) * 10000) : 0

	return {
		c,
		terms,
		fx,
		wire,
		anomaly,
		targetCcy,
		deductedFeesMinor,
		normalizedWithholdingTaxMinor,
		varianceMinor,
		recoverableOurViolationMinor,
		optimalTransparentNetMinor,
		totalLeakMinor,
		totalLeakBps,
	}
}

export const verifySettlementBalanceTool: Tool = {
	type: "function",
	name: "verify_settlement_balance",
	description: "Deterministically cross-check TermsAgent, FxBenchmarkAgent, WireDetectiveAgent, and DuplicateAnomalyAgent in integer minor units.",
	parameters: {
		type: "object",
		properties: { caseId: { type: "string" } },
		required: ["caseId"],
	},
	strict: false,
	invoke: async (rawArgs: unknown) => {
		const { caseId } = CaseIdSchema.parse(rawArgs)
		const state = resolveRuntime().state
		const calc = computeCaseAuditNumbers(state, caseId)

		if (!calc) {
			return {
				caseId,
				error: "Specialist assessments incomplete before Auditor verification.",
			}
		}

		const {
			c,
			terms,
			fx,
			wire,
			anomaly,
			targetCcy,
			deductedFeesMinor,
			normalizedWithholdingTaxMinor,
			varianceMinor,
			recoverableOurViolationMinor,
		} = calc

		const duplicateDetected = anomaly?.classification === "TRUE_DUPLICATE"
		const recommendedAction =
			recoverableOurViolationMinor > 0
				? "FILE_OUR_FEE_DISPUTE"
				: varianceMinor !== 0 || duplicateDetected || Boolean(anomaly?.vendorBankChanged)
					? "ESCALATE_VARIANCE"
					: "CLOSE_CLEAN"

		const taxSegment =
			normalizedWithholdingTaxMinor > 0 ? ` - Tax ${formatMoney(normalizedWithholdingTaxMinor, targetCcy)}` : ""

		return {
			caseId,
			currency: targetCcy,
			midMarketExpectedMinor: fx.midMarketExpectedMinor,
			fxSpreadLossMinor: fx.fxSpreadLossMinor,
			fxSpreadBps: fx.fxSpreadBps,
			deductedFeesMinor,
			withholdingTaxMinor: normalizedWithholdingTaxMinor,
			settledMinor: c.wire.settledAmount.amountMinor,
			unexplainedVarianceMinor: varianceMinor,
			recoverableOurViolationMinor,
			duplicateDetected,
			ibanValid: terms.ibanValid ?? true,
			isOrphanMatched: wire.isOrphan && Boolean(wire.matchedInvoiceId),
			recommendedAction,
			summary: `Arithmetic using submitted values in ${targetCcy}: ECB reference ${formatMoney(fx.midMarketExpectedMinor, targetCcy)} - FX estimate ${formatMoney(fx.fxSpreadLossMinor, targetCcy)} - recorded fees ${formatMoney(deductedFeesMinor, targetCcy)}${taxSegment} - stated settlement ${formatMoney(c.wire.settledAmount.amountMinor, targetCcy)} => calculated variance ${formatMoney(varianceMinor, targetCcy)}. This is not independent bank confirmation.`,
		}
	},
}

export const verifyCitationsIntegrityTool: Tool = {
	type: "function",
	name: "verify_citations_integrity",
	description: "Check that specialist SourceRef entries contain the required identifying fields and excerpts. This structural check does not authenticate source documents or independently verify figures.",
	parameters: {
		type: "object",
		properties: { caseId: { type: "string" } },
		required: ["caseId"],
	},
	strict: false,
	invoke: async (rawArgs: unknown) => {
		const { caseId } = CaseIdSchema.parse(rawArgs)
		const state = resolveRuntime().state
		const terms = state.termsByCaseId.get(caseId)
		const fx = state.fxByCaseId.get(caseId)
		const wire = state.wireByCaseId.get(caseId)
		const anomaly = state.anomalyByCaseId.get(caseId)

		const allRefs = dedupeSourceRefs([
			...(terms?.sourceRefs ?? []),
			...(fx?.sourceRefs ?? []),
			...(wire?.sourceRefs ?? []),
			...(anomaly?.sourceRefs ?? []),
		])

		const validRefs = allRefs.filter(
			(r) => Boolean(r.sourceType && r.recordId && r.field && r.rawExcerpt.trim().length > 0),
		)
		const citationAuditPassed = validRefs.length >= 2

		return {
			caseId,
			citationAuditPassed,
			totalRefs: validRefs.length,
			sourceRefs: validRefs,
				summary: citationAuditPassed
					? `Citation structure PASSED: ${validRefs.length} SourceRef entries contain the required fields. Source documents and figures were not independently authenticated.`
					: "Citation structure FAILED: insufficient SourceRef entries with the required fields.",
		}
	},
}

